"""Long, winding campaign rooms (levels 7+), drawn as ASCII maps.

The maps are written the way the room is *seen*: the top row is the far wall (``z = depth - 1``) and the
bottom row is the wall behind the player (``z = 0``); columns run ``x = 0 .. width - 1`` left to right.
The outer ring of ``#`` is the lab wall (it is regenerated by ``make_level``), a ``D`` on that ring marks the
exit door, ``S`` the start.

Legend
------
``#`` wall            ``.`` floor           ``S`` start           ``D`` exit door (on the outer ring)
``~`` water           ``A`` acid            ``I`` ice             ``^`` floor spikes (always out)
``v`` timed spikes    ``c`` coin            ``p`` button          ``P`` hold-button (needs Deeba or a crate)
``b`` crate           ``r`` spinner         ``l`` lever           ``u`` lift (top 1.2)
``L`` low ledge       ``Q`` ledge + button  ``C`` ledge + coin    ``T`` tall tower ledge (needs a lift)
``j`` jump boost      ``s`` speed boost     ``f`` time freeze     ``h`` shield

Lasers, shocks and cutters take parameters, so they are passed in explicitly (see ``extras``).
"""

from typing import Any, Dict, List, Tuple

LEGEND_LISTS = {
    "~": "water", "A": "hazards", "I": "ice", "c": "coins", "p": "plates", "P": "plates", "b": "blocks",
    "r": "rotators", "l": "levers", "L": "platforms", "Q": "platforms", "C": "platforms", "T": "platforms",
}
POWERUPS = {"j": "jump", "s": "speed", "f": "freeze", "h": "shield"}


def ascii_level(name: str, hint: str, rows: List[str], extras: Dict[str, Any] | None = None) -> Dict[str, Any]:
    depth = len(rows)
    width = len(rows[0])
    assert all(len(r) == width for r in rows), f"{name}: ragged rows"
    spec: Dict[str, Any] = {"name": name, "hint": hint, "width": width, "depth": depth}
    lists: Dict[str, List[List[Any]]] = {}
    props: Dict[str, Dict[str, Any]] = {}

    def add(key: str, cell: List[Any]) -> None:
        lists.setdefault(key, []).append(cell)

    start = door = None
    for ri, line in enumerate(rows):
        z = depth - 1 - ri
        for x, ch in enumerate(line):
            border = x in (0, width - 1) or z in (0, depth - 1)
            cell = [x, z]
            if ch == "D":
                assert border, f"{name}: door must sit on the outer wall"
                door = cell
                continue
            if border:
                continue
            if ch == "S":
                start = cell
            elif ch == "#":
                add("walls", cell)
            elif ch == "^":
                add("spikes", [x, z, 0])
            elif ch == "v":
                add("spikes", [x, z, 3.0])
            elif ch == "u":
                add("lifts", [x, z, 1.2])
            elif ch in POWERUPS:
                add("powerups", [x, z, POWERUPS[ch]])
            elif ch in LEGEND_LISTS:
                add(LEGEND_LISTS[ch], cell)
                if ch == "P":
                    add("continuousPlates", cell)
                if ch in "QC":
                    add("coins" if ch == "C" else "plates", cell)
                if ch == "T":
                    props[f"platform:{x}:{z}"] = {"height": 2.0, "size": 0.95, "color": "#7fb6ff", "collision": True}
            elif ch in ". ":
                pass
            else:
                raise ValueError(f"{name}: unknown map symbol {ch!r} at {x},{z}")
    assert start and door, f"{name}: needs S and D"
    spec["start"] = start
    spec["exitDoor"] = door
    spec.update(lists)
    if props:
        spec["objectProperties"] = props
    for key, value in (extras or {}).items():
        if key == "objectProperties":
            spec.setdefault("objectProperties", {}).update(value)
        else:
            spec[key] = value
    spec.setdefault("rotatorSpeed", 1.0)
    return spec


def wire(spec: Dict[str, Any], source_kind: str, source_cell, targets: List[Tuple[str, List[int]]]) -> None:
    """Colour-code a button / lever with the obstacles it switches off (kinds: plate, lever, laser, shock, cutter, spikes, lift)."""
    props = spec.setdefault("objectProperties", {})
    channel = 1 + max([int(p.get("channel", 0)) for p in props.values()] + [0])
    props[f"{source_kind}:{source_cell[0]}:{source_cell[1]}"] = {**props.get(f"{source_kind}:{source_cell[0]}:{source_cell[1]}", {}), "channel": channel}
    for kind, cell in targets:
        key = f"{kind}:{cell[0]}:{cell[1]}"
        props[key] = {**props.get(key, {}), "channel": channel}


LONG_SPECS: List[Dict[str, Any]] = []


class Grid:
    """A tiny drawing canvas so long rooms can be laid out with rectangles instead of typing every row."""

    def __init__(self, width: int, depth: int):
        self.w, self.d = width, depth
        self.c = [["." for _ in range(width)] for _ in range(depth)]  # c[z][x]
        for x in range(width):
            self.c[0][x] = self.c[depth - 1][x] = "#"
        for z in range(depth):
            self.c[z][0] = self.c[z][width - 1] = "#"

    def set(self, x: int, z: int, ch: str) -> "Grid":
        self.c[z][x] = ch
        return self

    def rect(self, x0: int, z0: int, x1: int, z1: int, ch: str) -> "Grid":
        for z in range(z0, z1 + 1):
            for x in range(x0, x1 + 1):
                self.c[z][x] = ch
        return self

    def rows(self) -> List[str]:
        return ["".join(self.c[z]) for z in range(self.d - 1, -1, -1)]

    def show(self) -> str:
        return "\n".join(f"{z:>2} " + "".join(self.c[z]) for z in range(self.d - 1, -1, -1))


def _switchback() -> Dict[str, Any]:
    g = Grid(15, 21)
    # four turns: wall rows with the opening alternating right / left
    g.rect(1, 4, 11, 4, "#").rect(3, 8, 13, 8, "#").rect(1, 12, 11, 12, "#").rect(3, 16, 13, 16, "#")
    g.set(2, 2, "S").set(14, 18, "D")
    # lane A: timed spikes
    g.rect(6, 1, 6, 3, "v")
    for x, z in ((3, 1), (9, 3), (12, 2)):
        g.set(x, z, "c")
    # lane B: a pond to wade through, a patrolling saw
    g.rect(8, 5, 9, 7, "~")
    for x, z in ((11, 6), (3, 7)):
        g.set(x, z, "c")
    # lane C: an icy run and a one-cell acid trench to hop
    g.rect(4, 9, 9, 11, "I").rect(11, 9, 11, 11, "A")
    for x, z in ((7, 10), (12, 11)):
        g.set(x, z, "c")
    # lane D: a laser patrol, the door button hides in the corner
    g.set(2, 15, "p").set(3, 14, "c").set(10, 13, "c")
    # lane E: coins and the shock gate
    for x, z in ((4, 19), (12, 19)):
        g.set(x, z, "c")
    return ascii_level(
        "Switchback",
        "A long winding corridor: hop the spikes, wade the pond, slide the ice, dodge the laser, grab the button and beat the shock gate.",
        g.rows(),
        {
            "cutters": [[4, 6, "z", 1.0, 0.5, 1.0]],
            "lasers": [[7, 14, "x", 2.5, 1, "z", 0.5, 0.9]],
            "shocks": [[8, 17, "down", 3, 3.0, 3.0], [8, 18, "down", 3, 3.0, 3.0], [8, 19, "down", 3, 3.0, 3.0]],
            "timeLimit": 120,
        },
    )


def _crate_canyon() -> Dict[str, Any]:
    g = Grid(17, 27)
    TOWER = {"height": 2.0, "size": 0.95, "color": "#7fb6ff", "collision": True}
    g.set(2, 3, "S").set(8, 26, "D")
    # lane A: shove the crate onto the gold hold-button
    g.set(4, 3, "b").set(11, 3, "P")
    for x, z in ((6, 1), (13, 5)):
        g.set(x, z, "c")
    # lane B: a shock gate (powered down while the crate sits on the button) and a pond
    g.rect(1, 6, 12, 6, "#")
    g.rect(8, 7, 8, 7, "#").rect(8, 11, 8, 11, "#")
    g.rect(3, 8, 5, 10, "~")
    for x, z in ((11, 9), (2, 7)):
        g.set(x, z, "c")
    # lane C: an acid moat bridged by a ledge, a saw patrols beyond it
    g.rect(4, 12, 15, 12, "#")
    g.rect(7, 13, 9, 17, "A").rect(7, 15, 9, 15, "L").set(8, 15, "C")
    for x, z in ((3, 13), (13, 17)):
        g.set(x, z, "c")
    # lane D: lever -> lift -> tower button, then a spinner guards the door
    g.rect(1, 18, 12, 18, "#")
    g.rect(1, 22, 6, 22, "#").rect(10, 22, 15, 22, "#")
    g.rect(7, 21, 7, 22, "A").rect(9, 21, 9, 22, "A")
    g.set(8, 21, "u").set(8, 22, "Q").set(13, 20, "l").set(8, 24, "r")
    for x, z in ((3, 24), (13, 24), (5, 20)):
        g.set(x, z, "c")
    spec = ascii_level(
        "Crate Canyon",
        "Push the crate onto the gold button to power down the shock gate. Bridge the acid, pull the lever, ride the lift to the tower button, and slip past the spinner.",
        g.rows(),
        {
            "shocks": [[8, 8, "down", 3, 3.0, 3.0], [8, 9, "down", 3, 3.0, 3.0], [8, 10, "down", 3, 3.0, 3.0]],
            "cutters": [[13, 15, "z", 1.5, 0.5, 1.0]],
            "objectProperties": {"platform:8:22": TOWER},
            "rotatorSpeed": 1.1,
            "timeLimit": 150,
        },
    )
    wire(spec, "plate", [11, 3], [("shock", [8, 8]), ("shock", [8, 9]), ("shock", [8, 10])])
    return spec


